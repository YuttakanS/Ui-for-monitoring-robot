#!/usr/bin/env node
/*
 * Build the 3D-view models and write them for the web page (replaces the
 * Maya script build_models.py, 2026-11-25). Plain Node, no dependencies:
 *
 *     npm run models          (= node tools/models-src/build_models.js)
 *
 * Writes to web/models/:
 *     robot.obj   robot only, at the origin, photodiode 1 facing +X
 *     led.obj     one LED fixture, emitter at the origin
 *     frame.obj   the frame that holds the LEDs, in place
 *     models.js   the three OBJ files as JS strings, so the page can use them
 *                 when opened straight from disk (file://)
 *
 * Units are cm and +Z is up, the same as the web page's 3D view. z = 0 is the
 * floor. The page colours the parts by material name (usemtl), so no .mtl
 * file is written. Change the numbers below and run again when the real
 * sizes are known. tests/models.test.js checks that models.js matches this
 * script and that the LED rows match LEDS in web/js/monitor.js.
 */
'use strict';
var fs = require('fs');
var path = require('path');

var OUT = path.join(__dirname, '..', '..', 'web', 'models');

// ---- measured / from the firmware ------------------------------------------
var PD_HEIGHT = 1.0;        // photodiode centres above the floor (cm), not measured yet
var LED_ABOVE_PD = 92.0;    // LEDs above the photodiodes (cm), firmware p(k, 2) = 0.920 m
var LED_Z = PD_HEIGHT + LED_ABOVE_PD;
var LED_SPACING = 50.0;     // cm between neighbouring LEDs along x
var LED_SPACING_Y = 51.5;   // cm between the LED rows along y (measured 2026-11-24)
var FACE_TILT = 30.0;       // side faces from horizontal (firmware be = 60 deg at the
                            // time; the real faces are 35 deg, be = 55, see README)

// ---- robot (derived) --------------------------------------------------------
// A photodiode sits at the centroid of its face, which is at 1/3 of the
// pyramid height, so h = 3 * PD_HEIGHT. The inradius of the base then follows
// from the face tilt: r = h / tan(tilt).
var ROBOT_H = 3.0 * PD_HEIGHT;
var ROBOT_INR = ROBOT_H / Math.tan(rad(FACE_TILT));    // base inradius
var ROBOT_CIRC = 2.0 * ROBOT_INR;                      // base circumradius
var ROBOT_SIDE = 2.0 * Math.sqrt(3.0) * ROBOT_INR;     // base side (~18 cm)
var PD_RADIUS = 0.6;
var PD_DEPTH = 0.3;

// ---- LED fixture and frame (approximate) -------------------------------------
var LED_LENS_R = 1.0;       // dome under the housing
var LED_HOUSING_R = 2.2;
var LED_HOUSING_H = 1.8;
var BAR = 2.0;              // frame profile, 2 x 2 cm
var FRAME_HALF = 70.0;      // legs at x, y = +-70 cm
var BAR_Z = LED_Z + LED_HOUSING_H + BAR / 2.0;   // centre line of the top bars

function rad(d) { return d * Math.PI / 180; }
function sub(a, b) { return [a[0] - b[0], a[1] - b[1], a[2] - b[2]]; }
function cross(a, b) { return [a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0]]; }
function norm(a) { var l = Math.hypot(a[0], a[1], a[2]); return [a[0] / l, a[1] / l, a[2] / l]; }
function faceNormal(p) { return norm(cross(sub(p[1], p[0]), sub(p[2], p[0]))); }

// ---- OBJ writer ---------------------------------------------------------------
// A mesh is a list of parts { name, mtl, faces }; a face is { p: [points], n:
// [normals] } with the points counter-clockwise seen from outside.
function flat(points) { var n = faceNormal(points); return { p: points, n: points.map(function () { return n; }) }; }

function num(x) {
  var s = (Math.abs(x) < 5e-7 ? 0 : x).toFixed(6);
  return s === '-0.000000' ? '0.000000' : s;
}

function toObj(group, parts) {
  var lines = ['# Generated by tools/models-src/build_models.js - do not edit by hand.', '# Units: cm, +Z up.'];
  var nv = 0, nn = 0;
  parts.forEach(function (part) {
    lines.push('g ' + group + ' ' + part.name, 'usemtl ' + part.mtl);
    var vIdx = {}, nIdx = {}, vOut = [], nOut = [], fOut = [];
    part.faces.forEach(function (f) {
      fOut.push('f ' + f.p.map(function (p, i) {
        var vk = p.map(num).join(' '), nk = f.n[i].map(num).join(' ');
        if (!(vk in vIdx)) { vOut.push('v ' + vk); vIdx[vk] = ++nv; }
        if (!(nk in nIdx)) { nOut.push('vn ' + nk); nIdx[nk] = ++nn; }
        return vIdx[vk] + '//' + nIdx[nk];
      }).join(' '));
    });
    Array.prototype.push.apply(lines, vOut.concat(nOut, fOut));
  });
  return lines.join('\n') + '\n';
}

// ---- shapes -------------------------------------------------------------------
// Cylinder of radius r from base point c along unit axis a, length h, segs sides,
// with smooth sides and flat caps.
function cylinder(c, a, r, h, segs) {
  var u = norm(Math.abs(a[2]) < 0.9 ? cross(a, [0, 0, 1]) : cross(a, [1, 0, 0]));
  var w = cross(a, u);
  var ring = function (t) {
    var res = [];
    for (var i = 0; i < segs; i++) {
      var ang = 2 * Math.PI * i / segs, d = [0, 1, 2].map(function (k) { return Math.cos(ang) * u[k] + Math.sin(ang) * w[k]; });
      res.push({ p: [0, 1, 2].map(function (k) { return c[k] + a[k] * t + d[k] * r; }), n: d });
    }
    return res;
  };
  var lo = ring(0), hi = ring(h), faces = [];
  var neg = [-a[0], -a[1], -a[2]];
  for (var i = 0; i < segs; i++) {
    var j = (i + 1) % segs;
    faces.push({ p: [lo[i].p, lo[j].p, hi[j].p, hi[i].p], n: [lo[i].n, lo[j].n, hi[j].n, hi[i].n] });
  }
  faces.push({ p: hi.map(function (q) { return q.p; }), n: hi.map(function () { return a; }) });
  faces.push({ p: lo.map(function (q) { return q.p; }).reverse(), n: lo.map(function () { return neg; }) });
  return faces;
}

// Lower half of a sphere of radius r centred at the origin (open at z = 0),
// segs around and bands from the equator to the bottom pole.
function lowerDome(r, segs, bands) {
  var pt = function (b, i) {
    var el = -Math.PI / 2 * b / bands, az = 2 * Math.PI * i / segs;
    var n = [Math.cos(el) * Math.cos(az), Math.cos(el) * Math.sin(az), Math.sin(el)];
    return { p: n.map(function (x) { return x * r; }), n: n };
  };
  var faces = [];
  for (var b = 0; b < bands; b++) {
    for (var i = 0; i < segs; i++) {
      var j = (i + 1) % segs;
      var q = b + 1 === bands ? [pt(b, i), pt(b + 1, 0), pt(b, j)]          // triangle at the pole
                              : [pt(b, i), pt(b + 1, i), pt(b + 1, j), pt(b, j)];
      faces.push({ p: q.map(function (x) { return x.p; }), n: q.map(function (x) { return x.n; }) });
    }
  }
  return faces;
}

// Axis-aligned box from min corner lo to max corner hi.
function box(lo, hi) {
  var P = function (x, y, z) { return [x ? hi[0] : lo[0], y ? hi[1] : lo[1], z ? hi[2] : lo[2]]; };
  return [
    [P(0, 0, 0), P(0, 1, 0), P(1, 1, 0), P(1, 0, 0)], // bottom
    [P(0, 0, 1), P(1, 0, 1), P(1, 1, 1), P(0, 1, 1)], // top
    [P(0, 0, 0), P(1, 0, 0), P(1, 0, 1), P(0, 0, 1)], // -y
    [P(0, 1, 0), P(0, 1, 1), P(1, 1, 1), P(1, 1, 0)], // +y
    [P(0, 0, 0), P(0, 0, 1), P(0, 1, 1), P(0, 1, 0)], // -x
    [P(1, 0, 0), P(1, 1, 0), P(1, 1, 1), P(1, 0, 1)]  // +x
  ].map(flat);
}

// Square bar of side BAR from p0 to p1 along one axis.
function bar(p0, p1) {
  var lo = [0, 1, 2].map(function (k) { return Math.min(p0[k], p1[k]) - (p0[k] === p1[k] ? BAR / 2 : 0); });
  var hi = [0, 1, 2].map(function (k) { return Math.max(p0[k], p1[k]) + (p0[k] === p1[k] ? BAR / 2 : 0); });
  return box(lo, hi);
}

// ---- models -------------------------------------------------------------------
function buildRobot() {
  // base corners at 60, 180, 300 deg: the edge between 300 and 60 faces +X
  var base = [60, 180, 300].map(function (a) { return [ROBOT_CIRC * Math.cos(rad(a)), ROBOT_CIRC * Math.sin(rad(a)), 0]; });
  var apex = [0, 0, ROBOT_H];
  var body = [0, 1, 2].map(function (i) { return flat([base[i], base[(i + 1) % 3], apex]); });
  body.push(flat([base[0], base[2], base[1]]));
  var parts = [{ name: 'robot_body', mtl: 'ra_body', faces: body }];
  // Firmware: v_l = (cos be cos al, -cos be sin al, sin be), al = 0, 120, -120 deg.
  // Face l's normal therefore points at azimuth -al.
  [0, 120, -120].forEach(function (al, l) {
    var az = rad(-al), el = rad(90 - FACE_TILT);
    var n = [Math.cos(el) * Math.cos(az), Math.cos(el) * Math.sin(az), Math.sin(el)];
    // face centroid: 1/3 of the way up, above the base edge midpoint; the
    // photodiode is a short cylinder centred PD_DEPTH / 2 out from the face
    var c = [ROBOT_INR * 2 / 3 * Math.cos(az), ROBOT_INR * 2 / 3 * Math.sin(az), ROBOT_H / 3];
    parts.push({ name: 'photodiode' + (l + 1), mtl: l === 0 ? 'ra_pd1' : 'ra_pd', faces: cylinder(c, n, PD_RADIUS, PD_DEPTH, 16) });
  });
  return toObj('robot', parts);
}

function buildLed() {
  return toObj('led_proto', [
    { name: 'led_proto_housing', mtl: 'ra_led_housing', faces: cylinder([0, 0, 0], [0, 0, 1], LED_HOUSING_R, LED_HOUSING_H, 24) },
    { name: 'led_proto_lens', mtl: 'ra_led_lens', faces: lowerDome(LED_LENS_R, 20, 6) }
  ]);
}

function buildFrame() {
  var F = FRAME_HALF, top = BAR_Z + BAR / 2, parts = [];
  [[-1, -1], [1, -1], [1, 1], [-1, 1]].forEach(function (s, i) {
    parts.push({ name: 'leg' + i, mtl: 'ra_frame', faces: bar([s[0] * F, s[1] * F, 0], [s[0] * F, s[1] * F, top]) });
  });
  // outer ring and the three bars the LED rows hang from (y = -51.5, 0, +51.5)
  [-F, -LED_SPACING_Y, 0, LED_SPACING_Y, F].forEach(function (y) {
    parts.push({ name: 'barX_' + String(y).replace('-', 'm').replace('.', 'p'), mtl: 'ra_frame', faces: bar([-F, y, BAR_Z], [F, y, BAR_Z]) });
  });
  [-F, F].forEach(function (x) {
    parts.push({ name: 'barY_' + String(x).replace('-', 'm'), mtl: 'ra_frame', faces: bar([x, -F, BAR_Z], [x, F, BAR_Z]) });
  });
  return toObj('frame', parts);
}

function build() {
  var obj = { robot: buildRobot(), led: buildLed(), frame: buildFrame() };
  var meta = {
    pdHeight: PD_HEIGHT, ledAbovePd: LED_ABOVE_PD, ledZ: LED_Z,
    robotHeight: +ROBOT_H.toFixed(3), robotSide: +ROBOT_SIDE.toFixed(3),
    robotInradius: +ROBOT_INR.toFixed(3), ledHousingH: LED_HOUSING_H,
    ledSpacing: LED_SPACING, ledSpacingY: LED_SPACING_Y, barZ: BAR_Z
  };
  var js = '// Generated by tools/models-src/build_models.js - do not edit by hand.\n' +
    '// OBJ text of the 3D view models, in cm, +Z up, z = 0 = floor.\n' +
    'window.RA_MODELS = ' + JSON.stringify({ meta: meta, obj: obj }, null, 1) + ';\n';
  return { obj: obj, meta: meta, js: js };
}

module.exports = { build: build };

if (require.main === module) {
  var res = build();
  Object.keys(res.obj).forEach(function (k) { fs.writeFileSync(path.join(OUT, k + '.obj'), res.obj[k]); });
  fs.writeFileSync(path.join(OUT, 'models.js'), res.js);
  console.log('robot: side ' + ROBOT_SIDE.toFixed(2) + ' cm, height ' + ROBOT_H.toFixed(2) +
    ' cm; LEDs at z = ' + LED_Z.toFixed(1) + ' cm, rows at y = +-' + LED_SPACING_Y + ' cm');
}
